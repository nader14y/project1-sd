# مرحله‌ی ۲ (دقیقه‌ی ۴۰ تا ۵۰) — چند سؤال با حلقه
#
# قبل از نوشتن، بپرسید: «حالا می‌خواهم ۳ سؤال داشته باشم. چه کار کنم؟»
# بگذارید یکی واقعاً کپی کند، بعد بگویید: «خب حالا ۳۰ سؤال. هنوز کپی می‌کنی؟»

questions = [
    ("پایتخت ژاپن کدام است؟", ["توکیو", "کیوتو", "اوساکا", "سئول"], "A"),
    ("خروجی len('سلام') چیست؟", ["3", "4", "5", "خطا"], "B"),
    ("بزرگ‌ترین سیاره‌ی منظومه‌ی شمسی؟", ["زمین", "زحل", "مشتری", "نپتون"], "C"),
]

for text, options, correct in questions:
    print(f"\n{text}")
    for letter, opt in zip("ABCD", options):
        print(f"  {letter}) {opt}")

    answer = input("جواب تو (A-D): ").strip().upper()

    if answer == correct:
        print("✅ درست!")
    else:
        print(f"❌ غلط! جواب درست: {correct}")


# ─────────────────────────────────────────────────────────────────────
# نکته‌ی گذری: zip("ABCD", options)
#
# اگر گیج شدند، همین را در ترمینال نشان بدهید:
#     >>> list(zip("ABCD", ["توکیو", "کیوتو", "اوساکا", "سئول"]))
#     [('A', 'توکیو'), ('B', 'کیوتو'), ('C', 'اوساکا'), ('D', 'سئول')]
#
# «حرف‌ها و گزینه‌ها را دوتا دوتا کنار هم می‌گذارد.»
