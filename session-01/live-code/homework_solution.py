# حل تمرین خانه‌ی جلسه‌ی ۱ — 🔒 فقط برای مربی، پخش نکنید
#
# سه خواسته‌ی تمرین:
#   ۱) کوییز را به ۵ سؤال برسانید
#   ۲) آخر بازی، درصد پاسخ درست را هم نشان دهید
#   ۳) شمارنده اضافه کنید: «سؤال ۲ از ۵»

questions = [
    ("پایتخت ژاپن کدام است؟", ["توکیو", "کیوتو", "اوساکا", "سئول"], "A"),
    ("خروجی len('سلام') چیست؟", ["3", "4", "5", "خطا"], "B"),
    ("بزرگ‌ترین سیاره‌ی منظومه‌ی شمسی؟", ["زمین", "زحل", "مشتری", "نپتون"], "C"),
    ("نماد شیمیایی طلا چیست؟", ["Ag", "Au", "Fe", "Gd"], "B"),
    ("شاهنامه اثر کیست؟", ["حافظ", "سعدی", "فردوسی", "مولوی"], "C"),
]

total = len(questions)          # ← کلید خواسته‌ی ۳: تعداد را از خود لیست بگیر، نه دستی
score = 0
correct_count = 0

for i, (text, options, correct) in enumerate(questions, start=1):
    print(f"\nسؤال {i} از {total}: {text}")
    for letter, opt in zip("ABCD", options):
        print(f"  {letter}) {opt}")

    answer = input("جواب تو (A-D): ").strip().upper()

    if answer == correct:
        print("✅ درست!")
        score += 10
        correct_count += 1
    else:
        print(f"❌ غلط! جواب درست: {correct}")

percent = correct_count / total * 100

print(f"\n🏁 بازی تمام شد!")
print(f"   امتیاز تو: {score}")
print(f"   درست: {correct_count} از {total}  ({percent:.0f}٪)")


# ─────────────────────────────────────────────────────────────────────
# نکته‌های تصحیح — دنبال این‌ها بگردید:
#
# ✅ خوب:  total = len(questions)
# ⚠️  قابل‌قبول ولی نقدپذیر:  total = 5   ← بپرسید: «اگر ۶ سؤال شد چه؟»
#            (این دقیقاً همان «عدد جادویی» است که جلسه‌ی ۵ سراغش می‌رویم)
#
# ✅ خوب:  correct_count / total * 100
# ❌ اشتباه رایج: score / total * 100      ← درصد امتیاز است نه درصد پاسخ درست
# ❌ اشتباه رایج: correct_count // total * 100  ← تقسیم صحیح، همیشه ۰ می‌دهد!
#            (اگر کسی این را داشت، هدیه است: در ترمینال 3 // 5 را نشانش بدهید)
#
# 💡 اگر کسی f"{percent:.0f}٪" را بلد نبود و از round() استفاده کرد، کاملاً قبول است.
